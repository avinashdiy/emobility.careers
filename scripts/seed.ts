async function seedJobs(adminUserId: string, companyIdBySlug: Map<string, string>) {
  console.log(`🌱 Seeding ${JOBS.length} EV jobs (engineer + technician tiers) across battery / charging / powertrain / motor / vehicle / software / manufacturing / fleet / after-sales...`);

  // Pre-fetch domain + skill ids by slug/name for cheap lookups inside the loop.
  const [domains, skills] = await Promise.all([
    db.eVDomain.findMany({ select: { id: true, slug: true } }),
    db.skill.findMany({ select: { id: true, name: true } }),
  ]);
  const domainIdBySlug = new Map(domains.map((d) => [d.slug, d.id]));
  const skillIdByName = new Map(skills.map((s) => [s.name.toLowerCase(), s.id]));

  // Wipe seed-marked jobs so re-running is idempotent. We tag the seed
  // with `applicationEmail = "seed@emobility.careers"` for detection.
  await db.jobPosting.deleteMany({ where: { applicationEmail: "seed@emobility.careers" } });

  let inserted = 0;
  for (const job of JOBS) {
    const companyId = companyIdBySlug.get(job.companySlug);
    if (!companyId) {
      console.warn(`   ! company ${job.companySlug} not found — skipping ${job.title}`);
      continue;
    }
    const slug = `${job.slugSeed}-${job.companySlug}`;
    const publishedAt = new Date(Date.now() - job.publishedDaysAgo * 24 * 60 * 60 * 1000);

    const evDomainIds = job.evDomainSlugs
      .map((s) => domainIdBySlug.get(s))
      .filter((x): x is string => !!x);
    const skillIds = job.skillNames
      .map((n) => skillIdByName.get(n.toLowerCase()))
      .filter((x): x is string => !!x);

    await db.jobPosting.create({
      data: {
        slug,
        companyId,
        postedById: adminUserId,
        title: job.title,
        description: job.description,
        responsibilities: job.responsibilities,
        requirements: job.requirements,
        benefits: job.benefits ?? null,
        profileMode: job.profileMode,
        employmentType: job.employmentType,
        workMode: job.workMode,
        seniorityLevel: job.seniorityLevel,
        locations: job.locations,
        experienceMin: job.experienceMin,
        experienceMax: job.experienceMax,
        salaryMin: job.salaryMin,
        salaryMax: job.salaryMax,
        salaryCurrency: "INR",
        salaryHidden: false,
        audience: job.audience ?? JobAudience.PUBLIC,
        status: JobStatus.OPEN,
        publishedAt,
        // Seed-tag — used by the deleteMany above so re-runs replace
        // these rows cleanly without touching real recruiter postings.
        applicationEmail: "seed@emobility.careers",
        // External career-page URL. The public job page checks this
        // first and routes the apply CTA out to the employer's own
        // ATS instead of using the internal apply form — appropriate
        // for aggregated listings where we don't own the funnel.
        applicationUrl: job.applicationUrl ?? null,
        evDomains: {
          create: evDomainIds.map((id) => ({ evDomainId: id })),
        },
        skills: {
          create: skillIds.map((id, i) => ({ skillId: id, required: i < 3, weight: 1 })),
        },
      },
    });
    inserted += 1;
  }
  console.log(`   → ${inserted} jobs seeded across ${new Set(JOBS.map((j) => j.companySlug)).size} companies`);
}

