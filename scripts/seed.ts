async function seedCompanies(adminUserId: string): Promise<Map<string, string>> {
  console.log(`🌱 Seeding ${COMPANIES.length} EV companies...`);
  const idBySlug = new Map<string, string>();
  for (const c of COMPANIES) {
    const company = await db.company.upsert({
      where: { slug: c.slug },
      create: {
        slug: c.slug,
        name: c.name,
        description: c.description,
        // `about` lights up the LinkedIn-style About section on
        // /company/[slug]. Falls back to undefined → null in Prisma.
        about: c.about ?? null,
        companyType: c.companyType,
        hqLocation: c.hqLocation,
        emailDomains: c.emailDomains,
        evDomains: c.evDomains,
        techStack: c.techStack,
        teamSize: c.teamSize ?? null,
        website: c.website ?? null,
        verificationStatus: CompanyVerification.VERIFIED,
        ownerUserId: adminUserId,
      },
      update: {
        name: c.name,
        description: c.description,
        // Re-runs replace `about` so editorial updates land on the next
        // seed without manual DB clean-up.
        about: c.about ?? null,
        companyType: c.companyType,
        hqLocation: c.hqLocation,
        emailDomains: c.emailDomains,
        evDomains: c.evDomains,
        techStack: c.techStack,
        teamSize: c.teamSize ?? null,
        website: c.website ?? null,
        verificationStatus: CompanyVerification.VERIFIED,
      },
      select: { id: true, slug: true },
    });
    idBySlug.set(company.slug, company.id);
  }
  console.log(`   → ${idBySlug.size} companies seeded`);
  return idBySlug;
}

