const PROFILE_MODE_FACTOR: Record<ProfileMode, { factor: number; yearsRange: [number, number] }> = {
  FRESHER:    { factor: 0.55, yearsRange: [0, 1] },
  EXPERIENCED:{ factor: 1.0,  yearsRange: [3, 7] },
  LEADERSHIP: { factor: 2.2,  yearsRange: [10, 18] },
  TECHNICIAN: { factor: 0.45, yearsRange: [1, 5] },
};

const LOCATIONS = ["Bengaluru", "Pune", "Chennai", "Hyderabad", "Mumbai", "New Delhi", "Gurugram", "Hosur"];

/**
 * Pseudo-random but seedable picker. We use the (companyIndex, roleIndex,
 * variantIndex) tuple to produce stable values so re-running the seed
 * doesn't churn the database with brand-new randomness — the same
 * inputs produce the same row.
 */
function stableRand(seed: number): number {
  // mulberry32 - tiny deterministic PRNG
  let t = (seed + 0x6d2b79f5) | 0;
  t = Math.imul(t ^ (t >>> 15), t | 1);
  t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}

async function seedSalaries(companyIdBySlug: Map<string, string>) {
  console.log(`🌱 Seeding salary submissions across ${ROLES.length} roles (engineer + technician tiers)...`);

  // Pre-fetch evDomain ids by slug.
  const domains = await db.eVDomain.findMany({ select: { id: true, slug: true } });
  const domainIdBySlug = new Map(domains.map((d) => [d.slug, d.id]));

  // Spread companies across roles. Each role gets ~8 submissions
  // distributed across companies + profile modes, biased toward the
  // tier-typical mode (EXPERIENCED for engineer roles, TECHNICIAN for
  // blue-collar). This mirrors what real Salary Compass submissions
  // tend to look like for India EV in 2026.
  const companies = COMPANIES.slice();
  let inserted = 0;
  let skipped = 0;
  // Wipe any existing seed-marked rows so re-running is idempotent.
  // We tag seed rows with `ip = "seed"` for easy detection.
  await db.salarySubmission.deleteMany({ where: { ip: "seed" } });

  for (let r = 0; r < ROLES.length; r++) {
    const role = ROLES[r];
    const evDomainId = domainIdBySlug.get(role.evDomain) ?? null;

    // Pick ~8 submissions per role. Variants depend on tier:
    //   • TECHNICIAN — all submissions stay in the TECHNICIAN profile
    //     mode. Different companyIndex values still give us company
    //     spread, but the salary band stays in blue-collar territory.
    //   • ENGINEER — mix of EXPERIENCED, FRESHER and LEADERSHIP to
    //     mirror white-collar reality.
    const variants: Array<{ mode: ProfileMode; companyIndex: number }> =
      role.tier === "TECHNICIAN"
        ? [
            { mode: ProfileMode.TECHNICIAN, companyIndex: 0 },
            { mode: ProfileMode.TECHNICIAN, companyIndex: 1 },
            { mode: ProfileMode.TECHNICIAN, companyIndex: 2 },
            { mode: ProfileMode.TECHNICIAN, companyIndex: 3 },
            { mode: ProfileMode.TECHNICIAN, companyIndex: 4 },
            { mode: ProfileMode.TECHNICIAN, companyIndex: 5 },
            { mode: ProfileMode.TECHNICIAN, companyIndex: 6 },
            { mode: ProfileMode.TECHNICIAN, companyIndex: 7 },
          ]
        : [
            { mode: ProfileMode.EXPERIENCED, companyIndex: 0 },
            { mode: ProfileMode.EXPERIENCED, companyIndex: 1 },
            { mode: ProfileMode.EXPERIENCED, companyIndex: 2 },
            { mode: ProfileMode.EXPERIENCED, companyIndex: 3 },
            { mode: ProfileMode.FRESHER,     companyIndex: 4 },
            { mode: ProfileMode.FRESHER,     companyIndex: 5 },
            { mode: ProfileMode.LEADERSHIP,  companyIndex: 6 },
            { mode: ProfileMode.LEADERSHIP,  companyIndex: 7 },
          ];

    for (let v = 0; v < variants.length; v++) {
      const variant = variants[v];
      const company = companies[(variant.companyIndex + r) % companies.length];
      const companyId = companyIdBySlug.get(company.slug) ?? null;
      const factor = PROFILE_MODE_FACTOR[variant.mode];
      const seed = r * 100 + v;

      // Spread the CTC across the role's range, modulated by profile mode.
      const lo = role.baseRange[0] * factor.factor;
      const hi = role.baseRange[1] * factor.factor;
      const ctc = Number((lo + (hi - lo) * stableRand(seed)).toFixed(1));
      const yearsExp = Math.round(
        factor.yearsRange[0] +
          (factor.yearsRange[1] - factor.yearsRange[0]) * stableRand(seed + 1),
      );
      const baseShare = 0.65 + 0.1 * stableRand(seed + 2); // 65-75% of CTC
      const baseLakhs = Number((ctc * baseShare).toFixed(1));
      const bonusLakhs = Number((ctc * 0.1 * stableRand(seed + 3)).toFixed(1));
      const esopLakhs = variant.mode === "LEADERSHIP" || variant.mode === "EXPERIENCED"
        ? Number((Math.max(0, ctc - baseLakhs - bonusLakhs)).toFixed(1))
        : null;
      const location = LOCATIONS[Math.floor(stableRand(seed + 4) * LOCATIONS.length)];

      try {
        await db.salarySubmission.create({
          data: {
            companyId,
            companyName: company.name,
            jobTitle: role.jobTitle,
            evDomainId,
            profileMode: variant.mode,
            yearsExp,
            location,
            ctcLakhs: ctc,
            baseLakhs,
            bonusLakhs,
            esopLakhs,
            currency: "INR",
            status: SalarySubmissionStatus.APPROVED,
            ip: "seed",
            cookieId: `seed-${r}-${v}`,
            reviewedAt: new Date(),
          },
        });
        inserted += 1;
      } catch (err) {
        skipped += 1;
        console.warn(`   ! skipped ${company.slug}/${role.jobTitle}/${variant.mode}: ${err instanceof Error ? err.message : err}`);
      }
    }
  }

  console.log(`   → ${inserted} salary submissions inserted (${skipped} skipped)`);
}

