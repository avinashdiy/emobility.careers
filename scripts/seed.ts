async function seedInstitutions(): Promise<void> {
  console.log(`🌱 Seeding ${INSTITUTIONS.length} EV institutions (universities / colleges / R&D / training)...`);
  let upserted = 0;
  for (const inst of INSTITUTIONS) {
    await db.institution.upsert({
      where: { slug: inst.slug },
      create: {
        slug: inst.slug,
        name: inst.name,
        type: inst.type,
        shortName: inst.shortName ?? null,
        city: inst.city ?? null,
        state: inst.state ?? null,
        country: inst.country ?? "IN",
        website: inst.website ?? null,
        about: inst.about ?? null,
        foundedYear: inst.foundedYear ?? null,
        affiliation: inst.affiliation ?? null,
        verificationStatus: InstitutionVerification.VERIFIED,
        verifiedAt: new Date(),
      },
      update: {
        name: inst.name,
        type: inst.type,
        shortName: inst.shortName ?? null,
        city: inst.city ?? null,
        state: inst.state ?? null,
        country: inst.country ?? "IN",
        website: inst.website ?? null,
        about: inst.about ?? null,
        foundedYear: inst.foundedYear ?? null,
        affiliation: inst.affiliation ?? null,
        verificationStatus: InstitutionVerification.VERIFIED,
      },
    });
    upserted += 1;
  }
  const byType = INSTITUTIONS.reduce<Record<string, number>>((acc, i) => {
    acc[i.type] = (acc[i.type] ?? 0) + 1;
    return acc;
  }, {});
  console.log(
    `   → ${upserted} institutions seeded · ` +
      Object.entries(byType)
        .map(([t, n]) => `${n} ${t.toLowerCase()}`)
        .join(" · "),
  );
}

