// ─── Salary band helpers ──────────────────────────────────────
// India-default lakhs (annual CTC). The bands reflect what we
// observed across EV employer listings in 2024–25; refresh as the
// market evolves. CXO bands are intentionally wide because the
// range across early-stage vs. late-stage EV companies is wide.

function band(min: number, median: number, max: number) {
  return {
    salaryMinLakhs: min,
    salaryMedianLakhs: median,
    salaryMaxLakhs: max,
  };
}

