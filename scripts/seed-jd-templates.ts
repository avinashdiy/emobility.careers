/**
 * Compose a full JD from a family blueprint + per-role overrides.
 * The overrides win where present; family defaults backfill the
 * rest. Result is the fully-shaped SeedJD the upsert needs.
 */
function compose(
  family: Family,
  override: Partial<SeedJD> &
    Pick<SeedJD, "slug" | "title" | "summary" | "overview"> & {
      keySkills: string[];
      typicalCompanies: string[];
      typicalIndustries: string[];
      experienceMinYears: number;
      experienceMaxYears: number;
      salaryMinLakhs: number | null;
      salaryMedianLakhs: number | null;
      salaryMaxLakhs: number | null;
    },
): SeedJD {
  // Spread override first, then apply family-level defaults only for
  // fields that aren't already set. The `?? family.X` fallbacks make
  // sure undefined overrides don't blow away the family default.
  return {
    ...override,
    alternativeTitles: override.alternativeTitles ?? [],
    collarType: override.collarType ?? family.collarType,
    seniority: override.seniority ?? family.defaultSeniority,
    functionalArea: override.functionalArea ?? family.functionalArea,
    responsibilities: override.responsibilities ?? family.baseResponsibilities,
    requirements: override.requirements ?? family.baseRequirements,
    preferredQualifications: override.preferredQualifications ?? family.basePreferred,
    tools: override.tools ?? family.baseTools,
    certifications: override.certifications ?? family.baseCerts,
    careerPath: override.careerPath ?? family.baseCareerPath,
    reportsTo: override.reportsTo ?? family.reportsTo,
    reports: override.reports ?? [],
    sampleInterviewQuestions: override.sampleInterviewQuestions ?? family.baseQuestions,
    salaryPeriod: override.salaryPeriod ?? SalaryPeriod.YEARLY,
    remoteFriendly: override.remoteFriendly ?? false,
    demandSignal: override.demandSignal ?? "High",
  } as SeedJD;
}

