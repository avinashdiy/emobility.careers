// ─── Driver ───────────────────────────────────────────────────

async function main() {
  console.log(`📋 Seeding ${JDS.length} EV JD templates...`);

  const domains = await db.eVDomain.findMany({
    select: { id: true, slug: true },
  });
  const domainBySlug = new Map(domains.map((d) => [d.slug, d.id]));

  const author = await db.user.findFirst({
    where: { role: "ADMIN" },
    select: { id: true },
    orderBy: { createdAt: "asc" },
  });

  let upserted = 0;
  for (const jd of JDS) {
    const evDomainId =
      (jd.evDomainSlug && domainBySlug.get(jd.evDomainSlug)) || null;

    const payload = {
      title: jd.title,
      alternativeTitles: jd.alternativeTitles,
      summary: jd.summary,
      overview: jd.overview,
      collarType: jd.collarType,
      seniority: jd.seniority,
      functionalArea: jd.functionalArea,
      evDomainId,
      typicalCompanies: jd.typicalCompanies,
      typicalIndustries: jd.typicalIndustries,
      responsibilities: jd.responsibilities,
      requirements: jd.requirements,
      preferredQualifications: jd.preferredQualifications,
      keySkills: jd.keySkills,
      tools: jd.tools,
      certifications: jd.certifications,
      experienceMinYears: jd.experienceMinYears,
      experienceMaxYears: jd.experienceMaxYears,
      salaryMinLakhs: jd.salaryMinLakhs,
      salaryMedianLakhs: jd.salaryMedianLakhs,
      salaryMaxLakhs: jd.salaryMaxLakhs,
      salaryCurrency: "INR",
      salaryPeriod: jd.salaryPeriod ?? SalaryPeriod.YEARLY,
      salaryRoleQuery: jd.salaryRoleQuery ?? null,
      careerPath: jd.careerPath,
      reportsTo: jd.reportsTo ?? null,
      reports: jd.reports ?? [],
      sampleInterviewQuestions: jd.sampleInterviewQuestions,
      demandSignal: jd.demandSignal ?? null,
      remoteFriendly: jd.remoteFriendly ?? false,
      growthOutlook: jd.growthOutlook ?? null,
    } as const;

    await db.jobDescriptionTemplate.upsert({
      where: { slug: jd.slug },
      create: {
        slug: jd.slug,
        ...payload,
        status: JDStatus.PUBLISHED,
        publishedAt: new Date(),
        authorId: author?.id ?? null,
      },
      update: {
        ...payload,
        // Preserve `status` + `publishedAt` if admin already
        // touched them via /admin/jd-templates — we don't want
        // re-running the seed to flip an archived row back to
        // published.
      },
    });
    upserted += 1;
  }

  const byCollar = JDS.reduce<Record<string, number>>((acc, j) => {
    acc[j.collarType] = (acc[j.collarType] ?? 0) + 1;
    return acc;
  }, {});
  console.log(
    `✓ ${upserted} JD templates seeded · ` +
      Object.entries(byCollar)
        .map(([k, v]) => `${v} ${k.toLowerCase()}`)
        .join(" · "),
  );
}

main()
  .catch((err) => {
    console.error("✗ JD seed failed:", err);
    process.exit(1);
  })
  .finally(async () => {
    await db.$disconnect();
  });
